console.log("LOOPING PERTAMA");
// nilai awal
let i = 0;
do {
    //i=i+2;
    i += 2;
    console.log(`${i} - I love coding`);
} while(i < 20);

console.log("LOOPING KEDUA");
// nilai awal
let j = 20;
while(j >= -20) { // Berjalan selama j lebih besar atau sama dengan -20
    console.log(`${j} - I will become a MERN Stack developer`);
    j -= 2;
}